let lang = "es";

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = next === "en" ? "en" : "es";
  document.documentElement.lang = lang;
  try {
    localStorage.setItem("mercadoalba-lang", lang);
  } catch {
    /* private mode */
  }
}

export function initLang() {
  let stored = null;
  try {
    stored = localStorage.getItem("mercadoalba-lang");
  } catch {
    stored = null;
  }
  setLang(stored === "en" ? "en" : "es");
}

export function t(key, vars = {}) {
  const bag = STRINGS[lang] || STRINGS.es;
  let text = bag[key] ?? STRINGS.es[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function applyStaticCopy() {
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  const langButton = document.querySelector("#lang");
  if (langButton) {
    langButton.textContent = t("lang");
    langButton.setAttribute("aria-label", t("lang-label"));
    langButton.setAttribute("aria-pressed", lang === "en" ? "true" : "false");
  }
}
